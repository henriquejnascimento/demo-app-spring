CREATE TABLE PRODUCT (
    ID_PRODUCT      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME            VARCHAR2(20) NOT NULL,
    DESCRIPTION     VARCHAR2(60) NOT NULL,
    STATUS          VARCHAR2(50) NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE
);

CREATE TABLE FILE_PROCESS (
    ID_FILE_PROCESS NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STATUS VARCHAR(80) NOT NULL,
    DESCRIPTION     VARCHAR2(500),
    FILES_FOUND     NUMBER,
    FILES_SENT      NUMBER,
    COMPLETION_DATE TIMESTAMP WITH TIME ZONE,
    CREATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE
);

CREATE TABLE FILE_STORAGE (
    ID_FILE_STORAGE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_FILE_PROCESS NUMBER,
    FILE_PATH       VARCHAR2(255) NOT NULL,
    FILE_NAME       VARCHAR2(255) NOT NULL,
    FILE_SIZE       NUMBER NOT NULL,
    FILE_HASH       VARCHAR2(64) NOT NULL,
    MIME_TYPE       VARCHAR2(255) NOT NULL,
    DESCRIPTION     VARCHAR2(500),
    CREATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE,

    CONSTRAINT FK_FILE_PROCESS FOREIGN KEY (ID_FILE_PROCESS)
            REFERENCES FILE_PROCESS(ID_FILE_PROCESS)
            ON DELETE CASCADE
);

CREATE INDEX IDX_FILE_STORAGE_FILE_PROCESS ON FILE_STORAGE(ID_FILE_PROCESS);
